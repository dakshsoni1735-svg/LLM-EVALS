import streamlit as st
import pandas as pd
import json, time
from pathlib import Path
from engine import load_documents, build_index, retrieve, evaluate_answer, run_batch

st.set_page_config(page_title="RAG Reliability Lab", page_icon="🧪", layout="wide")
st.title("🧪 RAG Reliability Lab")
st.caption("Evaluate RAG answers for relevance, grounding, retrieval quality and risk — without downloading an LLM or using an API key.")

with st.sidebar:
    st.header("⚙️ Retrieval settings")
    top_k = st.slider("Number of retrieved chunks (top-k)", 1, 8, 4)
    st.markdown("---")
    st.markdown("**No Ollama. No API key. No model download.**")
    st.caption("This version evaluates answers you paste from any AI assistant. Scores are transparent, deterministic text-based indicators — not a substitute for human review or semantic LLM judging.")

if "docs" not in st.session_state: st.session_state.docs = []
if "index" not in st.session_state: st.session_state.index = None
if "runs" not in st.session_state: st.session_state.runs = []

tab1, tab2, tab3 = st.tabs(["📚 Evaluate an answer", "📊 Results dashboard", "🧪 Batch evaluation"])

with tab1:
    st.subheader("1. Build your knowledge base")
    uploads = st.file_uploader("Upload PDF, TXT or Markdown files", type=["pdf","txt","md"], accept_multiple_files=True)
    use_sample = st.checkbox("Include sample company handbook", value=True)
    if st.button("Build knowledge base", type="primary"):
        docs = []
        for f in uploads or []:
            docs.extend(load_documents(f.name, f.getvalue()))
        if use_sample:
            p = Path("sample_data/company_handbook.txt")
            docs.extend(load_documents(p.name, p.read_bytes()))
        if docs:
            st.session_state.docs = docs
            st.session_state.index = build_index(docs)
            st.success(f"Knowledge base ready: {len(docs)} chunks from {len(set(d['source'] for d in docs))} file(s).")
        else:
            st.warning("Upload a document or select the sample handbook.")

    if st.session_state.index:
        st.success(f"Knowledge base loaded — {len(st.session_state.index)} chunks.")
        st.divider()
        st.subheader("2. Evaluate an AI answer")
        question = st.text_area("Question", "What is the company's annual leave policy?")
        answer = st.text_area("Paste the answer generated by ChatGPT, Gemini, Qwen, or another model", height=150,
                              placeholder="Paste an AI-generated answer here...")
        reference = st.text_area("Reference answer (optional, for answer coverage)", 
                                 "Employees receive 20 days of paid annual leave per calendar year.")
        if st.button("Retrieve evidence and evaluate", type="primary", disabled=not (question.strip() and answer.strip())):
            contexts = retrieve(question, st.session_state.index, top_k)
            metrics = evaluate_answer(question, answer, contexts, reference)
            run = {"question":question, "answer":answer, "reference":reference, "contexts":contexts,
                   "metrics":metrics, "top_k":top_k, "timestamp":time.strftime("%Y-%m-%d %H:%M:%S")}
            st.session_state.runs.insert(0, run)
            st.session_state.latest = run

    if "latest" in st.session_state:
        r = st.session_state.latest
        st.divider()
        st.subheader("Evaluation report")
        m = r["metrics"]
        cols = st.columns(4)
        for col, key, label in zip(cols, ["groundedness","answer_relevance","retrieval_precision","reference_coverage"],
                                   ["Groundedness","Answer relevance","Retrieval precision","Reference coverage"]):
            val = m.get(key)
            col.metric(label, "N/A" if val is None else f"{val:.0%}")
        st.metric("Unsupported-word risk", f"{m['unsupported_word_risk']:.0%}")
        st.caption(m["explanation"])
        with st.expander("View retrieved evidence", expanded=True):
            for i,c in enumerate(r["contexts"],1):
                st.markdown(f"**Chunk {i} · {c['source']} · similarity {c['score']:.3f}**")
                st.write(c["text"])
        with st.expander("View detailed scoring"):
            st.json(m)

with tab2:
    st.subheader("Evaluation history")
    if not st.session_state.runs:
        st.info("Evaluate at least one answer to see your dashboard.")
    else:
        rows=[]
        for i,r in enumerate(st.session_state.runs,1):
            rows.append({"Run":i,"Question":r["question"][:60],"Top-k":r["top_k"],
                         **{k:r["metrics"].get(k) for k in ["groundedness","answer_relevance","retrieval_precision","reference_coverage","unsupported_word_risk"]}})
        df=pd.DataFrame(rows)
        st.dataframe(df,use_container_width=True,hide_index=True)
        metric=st.selectbox("Metric trend",["groundedness","answer_relevance","retrieval_precision","reference_coverage","unsupported_word_risk"])
        plot=df[["Run",metric]].dropna().set_index("Run")
        if not plot.empty: st.line_chart(plot)
        st.download_button("Download results CSV",df.to_csv(index=False),"rag_evaluation_results.csv","text/csv")
        st.download_button("Download full reports JSON",json.dumps(st.session_state.runs,indent=2),"rag_evaluation_reports.json","application/json")
        if st.button("Clear history"):
            st.session_state.runs=[]
            st.session_state.pop("latest",None)
            st.rerun()

with tab3:
    st.subheader("Evaluate a dataset in one go")
    st.markdown("Upload a CSV with columns `question`, `answer`, and optionally `reference_answer`. Each row represents one model response.")
    template=pd.DataFrame([
        {"question":"What is the annual leave allowance?","answer":"Employees receive 20 paid annual leave days per year.","reference_answer":"Employees receive 20 days of paid annual leave per calendar year."},
        {"question":"How many sick leave days are provided?","answer":"Employees receive 8 paid sick leave days per year.","reference_answer":"Employees receive 8 days of paid sick leave per calendar year."}
    ])
    st.download_button("Download sample evaluation CSV",template.to_csv(index=False),"evaluation_dataset_template.csv","text/csv")
    batch_file=st.file_uploader("Upload evaluation CSV",type=["csv"],key="batchcsv")
    if batch_file and st.session_state.index:
        try:
            data=pd.read_csv(batch_file)
            st.dataframe(data.head(10),use_container_width=True)
            if st.button("Run batch evaluation",type="primary"):
                results=run_batch(data,st.session_state.index,top_k)
                out=pd.DataFrame(results)
                st.session_state.batch_results=out
                st.success(f"Evaluated {len(out)} rows.")
        except Exception as e: st.error(f"Could not process CSV: {e}")
    if "batch_results" in st.session_state:
        st.dataframe(st.session_state.batch_results,use_container_width=True)
        st.download_button("Download batch report",st.session_state.batch_results.to_csv(index=False),"batch_evaluation_report.csv","text/csv")

st.divider()
st.caption("Methodology: TF-IDF retrieval + transparent lexical overlap metrics. Treat scores as screening signals. For production-grade semantic evaluation, add a validated evaluator such as RAGAS/DeepEval and human-labelled test data.")
